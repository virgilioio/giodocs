/* ─── The ":" inline trigger predicate ─────────────────────────
 *
 * A pure function so it can be tested exhaustively without a DOM.
 * Given the text BEFORE the caret in the current block, returns:
 *   { open: true,  query }   the popup should be visible with `query`
 *   { open: false, query: "" } otherwise
 *
 * Rules (intentionally strict — ":" is common in prose):
 *  - The ":" must be at the start of the block, or preceded by
 *    whitespace. "word:foo" never triggers ("10:30", "Note: hi").
 *  - Require at least ONE character typed after the ":".
 *  - The query accepts letters, digits, hyphen and underscore
 *    only; anything else (including a space) closes it.
 *  - Cap the query at 24 characters.
 */
export function shouldOpenEmojiTrigger(
  textBeforeCaret: string,
): { open: boolean; query: string } {
  const NO = { open: false, query: "" } as const;
  // Find the last ":" in the text before the caret.
  const colon = textBeforeCaret.lastIndexOf(":");
  if (colon < 0) return NO;
  // Anything after the colon becomes the query. Only letters/digits/-/_.
  const query = textBeforeCaret.slice(colon + 1);
  if (query.length === 0) return NO;
  if (query.length > 24) return NO;
  if (!/^[A-Za-z0-9_-]+$/.test(query)) return NO;
  // The ":" must be at start of block or preceded by whitespace.
  if (colon > 0) {
    const prev = textBeforeCaret[colon - 1];
    if (!/\s/.test(prev)) return NO;
  }
  return { open: true, query };
}
