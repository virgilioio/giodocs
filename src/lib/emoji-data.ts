/* Normalise a query: lowercase, trim, and treat underscores as
 * hyphens so `:thumbs_up:` finds `thumbs-up`. */
function normQuery(q: string): string {
  return q.toLowerCase().trim().replace(/_/g, "-");
}

/* Ranking:
 *   0 — name starts with query (best)
 *   1 — keyword equals or starts with query
 *   2 — name contains query
 *   3 — keyword contains query
 * Ties broken by natural array order.
 */
function score(e: Emoji, q: string): number | null {
  const name = e.name;
  if (name.startsWith(q)) return 0;
  for (const k of e.keywords) {
    if (k === q || k.startsWith(q)) return 1;
  }
  if (name.includes(q)) return 2;
  for (const k of e.keywords) {
    if (k.includes(q)) return 3;
  }
  return null;
}

export function searchEmoji(query: string, limit = 40): Emoji[] {
  const q = normQuery(query);
  if (!q) return []; // empty query returns nothing; the picker handles the section view itself
  const scored: Array<{ e: Emoji; s: number; i: number }> = [];
  for (let i = 0; i < EMOJI.length; i++) {
    const s = score(EMOJI[i], q);
    if (s !== null) scored.push({ e: EMOJI[i], s, i });
  }
  scored.sort((a, b) => (a.s - b.s) || (a.i - b.i));
  return scored.slice(0, limit).map((x) => x.e);
}

